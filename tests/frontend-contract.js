/* Runs without dependencies through check_frontend.py. Browser helpers are injected by the runner. */
async function runFrontendChecks(){
  let assertions=0;
  const check=(condition,message)=>{assertions++;if(!condition)throw new Error(message);};
  const rejects=async(fn,message)=>{let rejected=false;try{await fn();}catch{rejected=true;}check(rejected,message);};
  const request=(path,body)=>PreviewAPI.request(path,body?{method:'POST',body}:{});
  const state=()=>request('/api/state');
  let initial=await state();
  check(initial.step==='idle' && initial.day===1,'Initial state is day 1, idle');
  check(initial.demo_shop.price===175000 && initial.demo_shop.stock===300,'Seed listing matches contract');
  check(initial.demo_shop.images.length===4,'Listing has four images');
  check(!JSON.stringify(initial).includes('unit_cost'),'Public view excludes unit cost');
  await request('/api/day/start',{});check((await state()).step==='negotiating','Day start is asynchronous');
  await rejects(()=>request('/api/decision',{card_id:'bad',action:'accept'}),'Decision rejected while negotiating');
  __clock+=6000;let s=await state();
  check(s.step==='awaiting_decision' && s.pending_card.kind==='offer','Negotiation reaches an offer');
  check(s.pending_card.package.voucher_pct===3 && s.pending_card.package.ads_daily_budget===45000,'D offer respects example limits');
  const first=await request('/api/events?after=0');const after=await request('/api/events?after=3');
  check(after.events.every(e=>e.seq>3),'Cursor returns only newer events');
  check(new Set(first.events.map(e=>e.seq)).size===first.events.length,'Event sequence is unique');
  check(first.events.every(e=>e.run_id===s.run_id),'Events are scoped to the run');
  await rejects(()=>request('/api/decision',{card_id:'wrong',action:'accept'}),'Stale card cannot be accepted');
  await request('/api/decision',{card_id:s.pending_card.card_id,action:'negotiate',note_vi:'Giảm voucher còn 2%.'});
  __clock+=2500;s=await state();check(s.pending_card.package.voucher_pct===2,'Negotiate produces second offer');
  await request('/api/decision',{card_id:s.pending_card.card_id,action:'accept'});s=await state();
  check(s.step==='content_review' && s.content_draft.version===1,'Accept reaches content review');
  check(s.content_draft.images.every(i=>i.status==='running'),'Image jobs start running');
  await rejects(()=>request('/api/content/apply',{cover_option:'A'}),'Cannot apply an unfinished cover');
  await rejects(()=>request('/api/content/retry',{feedback_vi:' '}),'Empty feedback rejected');
  __clock+=4000;s=await state();
  check(s.content_draft.images.every(i=>i.status==='done' && i.path),'Images settle to usable assets');
  check(s.content_draft.video.status==='failed','Preview explicitly handles unavailable video');
  await request('/api/content/retry',{feedback_vi:'Ảnh nền sáng hơn.'});s=await state();check(s.content_draft.version===2,'Retry increments version');
  __clock+=4000;await request('/api/content/retry',{feedback_vi:'Giữ rõ màu quạt.'});__clock+=4000;s=await state();
  check(s.content_draft.version===3 && s.content_draft.feedback_history.length===2,'Third version retains feedback');
  await rejects(()=>request('/api/content/retry',{feedback_vi:'Làm lại'}),'No fourth content version');
  await request('/api/content/apply',{cover_option:'B'});s=await state();
  check(s.step==='day_done','Applying finishes the day');
  check(s.demo_shop.images[0].includes('cover-b.svg'),'Chosen cover is applied');
  check(s.demo_shop_original.title===initial.demo_shop.title,'Original listing remains intact');
  check(s.demo_shop.active_voucher_pct===2,'Approved voucher is applied');
  await request('/api/night',{});s=await state();
  check(s.day===2 && s.step==='idle' && s.last_night.day===1,'Night advances to the next day');
  check(s.last_night.pref_candidates.length===1,'Feedback creates a preference candidate');
  const nightEvents=await request('/api/events?after=0');
  check(nightEvents.events.some(e=>e.type==='market_result' && e.data.metrics.shop_id==='D'),'Night metrics are available through events');
  await request('/api/day/start',{});__clock+=6000;s=await state();
  check(s.pending_card.kind==='question' && s.pending_card.package===null,'Active package receives a question-only card');
  await request('/api/decision',{card_id:s.pending_card.card_id,action:'accept',rule_answer:true});
  check((await state()).step==='day_done','Preference confirmation can finish the active-package day');
  await request('/api/night',{});await request('/api/day/start',{});__clock+=6000;s=await state();
  check(s.step==='day_done' && !s.pending_card && !!s.active_package,'An active package is not offered again after preference confirmation');
  // An unmodified first draft must not invent a seller preference for the next day.
  await request('/api/reset',{memory:true});await request('/api/day/start',{});__clock+=6000;s=await state();
  await request('/api/decision',{card_id:s.pending_card.card_id,action:'accept'});__clock+=4000;
  await request('/api/content/apply',{cover_option:'A'});await request('/api/night',{});
  await request('/api/day/start',{});__clock+=6000;s=await state();
  check(s.step==='day_done' && !s.pending_card,'No preference question appears without seller feedback');
  // A declined preference is not asked again the next day.
  await request('/api/reset',{memory:true});await request('/api/day/start',{});__clock+=6000;s=await state();
  await request('/api/decision',{card_id:s.pending_card.card_id,action:'accept'});__clock+=4000;
  await request('/api/content/retry',{feedback_vi:'Ảnh nền sáng hơn.'});__clock+=4000;
  await request('/api/content/apply',{cover_option:'A'});await request('/api/night',{});
  await request('/api/day/start',{});__clock+=6000;s=await state();
  await request('/api/decision',{card_id:s.pending_card.card_id,action:'accept',rule_answer:false});
  await request('/api/night',{});await request('/api/day/start',{});__clock+=6000;s=await state();
  check(s.step==='day_done' && !s.pending_card,'Declining a preference suppresses the next-day question');
  const oldRun=(await state()).run_id;
  await request('/api/reset',{memory:false,seed:42});s=await state();
  check(s.day===1 && !s.memory_enabled && s.run_id!==oldRun,'Reset creates a fresh run with memory off');
  check((await request('/api/events?after=0')).events.length===0,'Reset clears events');
  await request('/api/day/start',{});__clock+=6000;s=await state();
  await request('/api/decision',{card_id:s.pending_card.card_id,action:'reject'});s=await state();
  check(s.step==='day_done' && !s.content_draft && !s.active_package,'Reject finishes without changing listing or spend');
  await request('/api/night',{});s=await state();
  check(s.last_night.lesson_ops.length===0 && s.last_night.history_updates.length===0,'Memory off produces no learned updates');
  const proof=await request('/api/proof');
  check(proof.metrics.length===4 && proof.days===6,'Proof report has six-day comparison metrics');
  check(proof.note_vi.includes('minh họa'),'Preview proof is clearly labeled illustrative');
  check(App.vnd(45000)==='45.000đ','Currency formatting is Vietnamese');
  check(App.dec(6.5)==='6,5','Decimal formatting is Vietnamese');
  check(App.vnd(null)==='—' && App.dec(undefined)==='—','Missing metrics are not shown as zero');
  check(App.escapeHtml('<img src=x onerror="alert(1)">').includes('&lt;img'),'User text is escaped');
  check(App.safeUrl('javascript:alert(1)')==='','Unsafe media URLs are rejected');
  check(App.changedFields(s.demo_shop,s.demo_shop_original).length===0,'Reset and rejection preserve the listing');
  check(App.pageUrl('demo.html').includes('preview=1'),'Navigation preserves preview mode');
  check(App.preview===true,'Preview is explicit');
  // Reload the shared layer in API mode and verify the transport independently of fixtures.
  location.search='?preview=0';__reloadCommon();let sent;
  globalThis.fetch=async(path,options)=>{sent={path,options};return{ok:true,json:async()=>({step:'content_review'})};};
  await App.api('/api/decision',{method:'POST',body:{card_id:'D-1',action:'accept'}});
  check(!App.preview,'API mode does not use browser fixtures');
  check(sent.path==='/api/decision' && sent.options.credentials==='same-origin','API uses the existing same-origin session cookie');
  check(sent.options.headers['Content-Type']==='application/json','JSON content type is set');
  check(JSON.parse(sent.options.body).card_id==='D-1','Request body follows API contract');
  // Use an unrelated backend product to catch any listing data left in the template.
  const databaseShop={...initial.demo_shop,shop_id:'Z',name:'Shop Ánh Dương <b>',title:'Đèn bàn USB & đế gỗ',description:'Đèn bàn có đế gỗ.',category:'den_ban',price:299000,stock:17,rating:4.9,images:['/media/lamp-1.jpg'],attributes:['Sạc USB','2 màu: Đen, Nâu'],active_voucher_pct:7};
  const databaseState={...initial,run_id:'database-run',demo_shop:databaseShop,demo_shop_original:databaseShop};
  globalThis.fetch=async()=>({ok:true,json:async()=>databaseState});
  const loaded=await App.api('/api/state');const listing=App.product(loaded.demo_shop);
  check(loaded.run_id==='database-run','API mode returns the backend state without fixture substitution');
  check(listing.includes('299.000đ') && listing.includes('<strong>17</strong>'),'Listing price and stock come from backend data');
  check(listing.includes('Shop Ánh Dương &lt;b&gt;') && listing.includes('Đèn bàn USB &amp; đế gỗ'),'Backend shop and product names are escaped and rendered');
  check(!listing.includes('Nhà Bé Lan') && !listing.includes('Quạt mini'),'An unrelated database product does not retain seed product labels');
  check(listing.includes('/media/lamp-1.jpg') && listing.includes('den_ban'),'Image path and category come from the backend product');
  check(listing.includes('data-color="Đen"') && listing.includes('data-color="Nâu"') && !listing.includes('data-color="Hồng"'),'Color choices are derived from backend attributes');
  check(!App.product({...databaseShop,attributes:['Sạc USB']}).includes('data-color='),'A product without color attributes does not invent variants');
  const signal=App.insight(loaded,[{type:'opportunity',data:{keyword:'đèn bàn USB',growth_7d_pct:37}}]);
  check(signal.includes('đèn bàn USB') && signal.includes('+37%'),'Opportunity keyword and growth use event data');
  check(!App.insight(loaded).includes('+240%'),'No example growth number appears without a backend signal');
  check(App.control(loaded).includes('Shop Ánh Dương &lt;b&gt;'),'Demo instructions use the current shop name');
  check(App.product({...databaseShop,images:[]}).includes('product-placeholder.svg'),'Missing product images use a neutral placeholder');
  globalThis.fetch=async()=>({ok:false,status:409,json:async()=>({error:{code:'stale',message_vi:'Thẻ đã hết hạn.'}})});
  let error='';try{await App.api('/api/decision');}catch(e){error=e.message;}
  check(error==='Thẻ đã hết hạn.','Backend errors are shown using message_vi');
  globalThis.fetch=async()=>{throw new Error('Network unavailable');};
  await rejects(()=>App.api('/api/state'),'Network failure does not silently switch to preview');
  check(App.preview===false,'API failure preserves the selected data source');
  return {assertions,passed:true};
}
